function renderArtwork(root) {
  const layers = artworkLayers[root.dataset.art];
  if (!layers) {
    return;
  }

  for (const layer of layers) {
    const image = document.createElement("img");
    image.className = "art-layer";
    image.src = `assets/${layer.file}`;
    image.alt = "";
    image.draggable = false;
    image.style.setProperty("--layer-inset", layer.inset);
    if (layer.opacity !== undefined) {
      image.style.setProperty("--layer-opacity", layer.opacity);
    }
    root.append(image);
  }
}

document.querySelectorAll(".artwork[data-art]").forEach(renderArtwork);

document.querySelectorAll(".menu-toggle").forEach((toggle) => {
  toggle.addEventListener("click", () => {
    const nav = document.getElementById(toggle.getAttribute("aria-controls"));
    const expanded = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-expanded", String(!expanded));
    toggle.setAttribute("aria-label", expanded ? "Open navigation" : "Close navigation");
    nav?.classList.toggle("is-open", !expanded);
  });
});

const signupForm = document.getElementById("signup-form");
if (signupForm) {
  signupForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const formData = new FormData(signupForm);
    const message = document.getElementById("signup-message");
    if (formData.get("password") !== formData.get("confirm-password")) {
      message.textContent = "Passwords do not match.";
      signupForm.elements.namedItem("confirm-password").setCustomValidity("Passwords do not match.");
      signupForm.reportValidity();
      return;
    }

    signupForm.elements.namedItem("confirm-password").setCustomValidity("");
    message.textContent = "Your details are ready to submit.";
  });

  signupForm.elements.namedItem("confirm-password").addEventListener("input", (event) => {
    event.currentTarget.setCustomValidity("");
  });
}

const accountForm = document.getElementById("account-form");
if (accountForm) {
  accountForm.addEventListener("submit", (event) => {
    event.preventDefault();
    document.getElementById("account-message").textContent = "Your changes have been saved.";
  });
}
